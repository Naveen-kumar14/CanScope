#!/usr/bin/env python3
"""Generate the CANScope protocol constants for firmware and dashboard.

Single source of truth: protocol/canscope_protocol.json.

    python tools/protocol/gen_protocol.py          # (re)write generated files
    python tools/protocol/gen_protocol.py --check  # exit 1 if any file is stale

Outputs (never edit by hand):
    firmware/common/canscope_protocol/protocol_spec.h
    dashboard/src/lib/protocol-spec.generated.ts
    test/protocol/protocol_vectors.generated.h
    dashboard/tests/protocol-vectors.generated.ts

Golden vectors are computed here by an independent, generic encoder so that the
hand-written C++ encoder and the TypeScript decoder are both checked against
the same bytes.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
SPEC = ROOT / "protocol" / "canscope_protocol.json"
OUT_H = ROOT / "firmware" / "common" / "canscope_protocol" / "protocol_spec.h"
OUT_TS = ROOT / "dashboard" / "src" / "lib" / "protocol-spec.generated.ts"
OUT_VEC_H = ROOT / "test" / "protocol" / "protocol_vectors.generated.h"
OUT_VEC_TS = ROOT / "dashboard" / "tests" / "protocol-vectors.generated.ts"

HEADER = "GENERATED by tools/protocol/gen_protocol.py from protocol/canscope_protocol.json. DO NOT EDIT."


def camel(name: str) -> str:
    """'MOTOR_TEMP_HIGH' / 'heartbeat_stop' / 'motorTempC' -> 'MotorTempHigh' / 'HeartbeatStop' / 'MotorTempC'."""
    if "_" in name or name.isupper():
        return "".join(p.capitalize() for p in name.lower().split("_"))
    return name[0].upper() + name[1:]


def checksum(can_id: int, b: list[int]) -> int:
    s = (can_id >> 8) + (can_id & 0xFF) + sum(b[:7])
    return (~s) & 0xFF


def encode(msg: dict, values: dict, counter: int) -> list[int]:
    b = [0] * msg["dlc"]
    for f in msg["fields"]:
        raw = values[f["key"]]
        n = f["length"]
        if raw < 0:
            raw += 1 << (8 * n)
        for i in range(n):
            b[f["start"] + i] = (raw >> (8 * (n - 1 - i))) & 0xFF
    b[msg["counterByte"]] = counter & 0xFF
    b[msg["checksumByte"]] = checksum(msg["canId"], b)
    return b


def validate_spec(spec: dict) -> None:
    ids = set()
    for m in spec["messages"]:
        assert m["canId"] <= 0x7FF, m["name"]
        assert m["canId"] not in ids, f"duplicate CAN ID {m['canId']:#x}"
        ids.add(m["canId"])
        assert m["dlc"] == 8
        used = {m["counterByte"], m["checksumByte"]}
        for f in m["fields"]:
            span = set(range(f["start"], f["start"] + f["length"]))
            assert not (span & used), f"overlap in {m['name']}.{f['key']}"
            used |= span
            bits = 8 * f["length"]
            lo, hi = (-(1 << (bits - 1)), (1 << (bits - 1)) - 1) if f["signed"] else (0, (1 << bits) - 1)
            assert lo <= f["validMin"] <= f["validMax"] <= hi, f"range of {f['key']}"
    # Legacy test-sketch IDs must stay distinguishable from protocol IDs.
    for legacy in (0x201, 0x202, 0x203, 0x210):
        assert legacy not in ids, f"protocol ID collides with legacy test ID {legacy:#x}"
    codes = [f["code"] for f in spec["faults"]]
    for t in spec["thresholds"]:
        assert t["fault"] in codes, t["fault"]
    for d in spec["demoFaults"]:
        for e in d["expected"]:
            assert e in codes, e


def telemetry(spec: dict) -> list[dict]:
    return [m for m in spec["messages"] if m["kind"] == "telemetry"]


def heartbeats(spec: dict) -> list[dict]:
    return [m for m in spec["messages"] if m["kind"] == "heartbeat"]


def field_by_key(spec: dict, key: str) -> dict:
    for m in telemetry(spec):
        for f in m["fields"]:
            if f["key"] == key:
                return f
    raise KeyError(key)


def vectors(spec: dict) -> list[dict]:
    """Deterministic golden vectors: defaults, both range limits, a negative value."""
    out = []
    for m in telemetry(spec):
        sets = [
            ("defaults", {f["key"]: f["default"] for f in m["fields"]}, 0),
            ("min", {f["key"]: f["validMin"] for f in m["fields"]}, 1),
            ("max", {f["key"]: f["validMax"] for f in m["fields"]}, 255),
        ]
        neg = {f["key"]: (-123 if f["signed"] else f["default"]) for f in m["fields"]}
        sets.append(("negative", neg, 77))
        for label, vals, ctr in sets:
            out.append({"label": f"{m['name']} {label}", "message": m["name"], "canId": m["canId"],
                        "values": [vals[f["key"]] for f in m["fields"]], "counter": ctr,
                        "bytes": encode(m, vals, ctr)})
    for m in heartbeats(spec):
        node_id = m["fields"][1]["validMin"]
        vals = {"protocolVersion": spec["protocolVersion"], "nodeId": node_id, "fwMajor": 1,
                "fwMinor": 0, "fwPatch": 0, "canState": 0}
        out.append({"label": f"{m['name']} v1", "message": m["name"], "canId": m["canId"],
                    "values": [vals[f["key"]] for f in m["fields"]], "counter": 9,
                    "bytes": encode(m, vals, 9)})
    return out


# --------------------------------------------------------------------------- C++

def gen_header(spec: dict) -> str:
    t = spec["timing"]
    s = spec["serial"]
    L = [f"// {HEADER}", "// Human-readable spec: docs/protocol/canscope-protocol-v1.md", "#pragma once", "",
         "#include <stddef.h>", "#include <stdint.h>", "", "namespace canscope {", "namespace proto {", ""]
    L += [f"static const uint8_t kProtocolVersion = {spec['protocolVersion']};",
          f"static const uint8_t kSerialProtocolVersion = {spec['serialProtocolVersion']};",
          f"static const uint8_t kBadProtocolVersion = {spec['badProtocolVersion']};  // demo fault only",
          f"static const uint32_t kBitrate = {spec['bus']['bitrate']};", ""]
    L.append("// Serial link")
    for k, v in s.items():
        L.append(f"static const uint32_t kSerial{camel(k)} = {v};")
    L.append("")
    L.append("// Timing (milliseconds unless stated)")
    for k, v in t.items():
        L.append(f"static const uint32_t k{camel(k)} = {v};")
    L.append("")
    L.append("// Node identities")
    for n in spec["nodes"]:
        L.append(f"static const uint8_t kNodeId{camel(n['name'])} = {n['id']};")
    L.append("")
    for m in spec["messages"]:
        p = camel(m["name"])
        L.append(f"// {m['name']}: sender {m['sender']}, every {m['periodMs']} ms")
        L.append(f"static const uint32_t k{p}Id = 0x{m['canId']:03X};")
        L.append(f"static const uint8_t k{p}Dlc = {m['dlc']};")
        L.append(f"static const uint32_t k{p}PeriodMs = {m['periodMs']};")
    hb = heartbeats(spec)[0]
    L += ["", "// Shared payload layout", f"static const uint8_t kCounterByte = {hb['counterByte']};",
          f"static const uint8_t kChecksumByte = {hb['checksumByte']};"]
    for f in hb["fields"]:
        L.append(f"static const uint8_t kHb{camel(f['key'])}Byte = {f['start']};")
    L.append("")
    L.append("// Telemetry fields: raw-integer limits (physical = raw * factor)")
    for m in telemetry(spec):
        for f in m["fields"]:
            p = camel(f["key"])
            L.append(f"static const uint8_t k{p}Start = {f['start']};")
            L.append(f"static const uint8_t k{p}Length = {f['length']};")
            L.append(f"static const int32_t k{p}Min = {f['validMin']};")
            L.append(f"static const int32_t k{p}Max = {f['validMax']};")
            L.append(f"static const int32_t k{p}Default = {f['default']};")
            L.append(f"static const uint8_t k{p}Decimals = {f['decimals']};  // unit: {f['unit']}")
    L.append("")

    keys = [f["key"] for m in telemetry(spec) for f in m["fields"]]
    L.append("enum class FieldId : uint8_t {")
    L += [f"  {camel(k)}," for k in keys]
    L += ["  Count", "};", ""]
    L.append("struct FieldInfo {\n  FieldId id;\n  const char* key;\n  uint8_t node_id;\n  uint8_t start;\n"
             "  uint8_t length;\n  bool is_signed;\n  int32_t min;\n  int32_t max;\n  int32_t def;\n"
             "  uint8_t decimals;\n  const char* unit;\n};")
    L.append("static const FieldInfo kFields[] = {")
    for m in telemetry(spec):
        nid = next(n["id"] for n in spec["nodes"] if n["name"] == m["sender"])
        for f in m["fields"]:
            L.append(f"    {{FieldId::{camel(f['key'])}, \"{f['key']}\", {nid}, {f['start']}, {f['length']}, "
                     f"{'true' if f['signed'] else 'false'}, {f['validMin']}, {f['validMax']}, {f['default']}, "
                     f"{f['decimals']}, \"{f['unit']}\"}},")
    L += ["};", f"static const size_t kFieldCount = {len(keys)};", ""]

    L.append("enum class Severity : uint8_t {")
    L += [f"  {camel(x)}," for x in spec["severities"]]
    L += ["};", ""]
    L.append("enum class FaultCode : uint8_t {")
    L += [f"  {camel(f['code'])}," for f in spec["faults"]]
    L += ["  Count", "};", ""]
    L.append("struct FaultInfo {\n  FaultCode code;\n  const char* name;\n  Severity severity;\n"
             "  bool monitor_scope;  // true: about the monitor itself, false: about one ECU\n};")
    L.append("static const FaultInfo kFaults[] = {")
    for f in spec["faults"]:
        L.append(f"    {{FaultCode::{camel(f['code'])}, \"{f['code']}\", Severity::{camel(f['severity'])}, "
                 f"{'true' if f['scope'] == 'monitor' else 'false'}}},")
    L += ["};", f"static const size_t kFaultCount = {len(spec['faults'])};", ""]

    L.append("enum class Compare : uint8_t { Ge, Le, AbsGe };")
    L.append("struct ThresholdDef {\n  FaultCode fault;\n  uint8_t node_id;\n  FieldId field;\n  Compare compare;\n"
             "  int32_t raise;  // raw units\n  int32_t clear;  // raw units (hysteresis)\n};")
    L.append("static const ThresholdDef kThresholds[] = {")
    cmp = {"ge": "Ge", "le": "Le", "abs_ge": "AbsGe"}
    for th in spec["thresholds"]:
        nid = next(n["id"] for n in spec["nodes"] if n["name"] == th["node"])
        L.append(f"    {{FaultCode::{camel(th['fault'])}, {nid}, FieldId::{camel(th['field'])}, "
                 f"Compare::{cmp[th['compare']]}, {th['raise']}, {th['clear']}}},")
    L += ["};", f"static const size_t kThresholdCount = {len(spec['thresholds'])};", ""]

    L.append("enum class DemoFault : uint8_t {")
    L.append("  None,")
    L += [f"  {camel(d['name'])}," for d in spec["demoFaults"]]
    L += ["  Count", "};", ""]
    L.append("static const char* const kDemoFaultNames[] = {")
    L.append('    "none",')
    L += [f'    "{d["name"]}",' for d in spec["demoFaults"]]
    L += ["};", ""]
    L.append("// What the monitor must detect for each demo fault (from \"expected\").")
    L.append("struct DemoFaultExpect {\n  DemoFault fault;\n  FaultCode codes[4];\n  uint8_t count;\n};")
    L.append("static const DemoFaultExpect kDemoFaultExpect[] = {")
    for d in spec["demoFaults"]:
        codes = [f"FaultCode::{camel(c)}" for c in d["expected"]]
        assert len(codes) <= 4
        padded = codes + ["FaultCode::Count"] * (4 - len(codes))
        L.append(f"    {{DemoFault::{camel(d['name'])}, {{{', '.join(padded)}}}, {len(codes)}}},")
    L += ["};", f"static const size_t kDemoFaultExpectCount = {len(spec['demoFaults'])};", ""]
    L.append("static const char* const kCanStateNames[] = {" + ", ".join(f'"{x}"' for x in spec["canStates"]) + "};")
    L.append(f"static const uint8_t kCanStateMax = {len(spec['canStates']) - 1};")
    L.append("static const char* const kProfileNames[] = {" + ", ".join(f'"{x}"' for x in spec["profiles"]) + "};")
    L.append(f"static const size_t kProfileCount = {len(spec['profiles'])};")
    L.append("")
    L.append("// ECU command parameter -> telemetry field")
    L.append("struct CommandParam {\n  uint8_t node_id;\n  const char* param;\n  FieldId field;\n};")
    L.append("static const CommandParam kCommandParams[] = {")
    count = 0
    for node, params in spec["ecuCommands"].items():
        nid = next(n["id"] for n in spec["nodes"] if n["name"] == node)
        for p in params:
            L.append(f"    {{{nid}, \"{p['param']}\", FieldId::{camel(p['field'])}}},")
            count += 1
    L += ["};", f"static const size_t kCommandParamCount = {count};", ""]
    L += ["}  // namespace proto", "}  // namespace canscope", ""]
    return "\n".join(L)


def gen_vec_h(spec: dict) -> str:
    v = vectors(spec)
    L = [f"// {HEADER}", "#pragma once", "", "#include <stdint.h>", "",
         "struct ProtocolVector {\n  const char* label;\n  uint32_t can_id;\n  int32_t values[6];\n"
         "  uint8_t value_count;\n  uint8_t counter;\n  uint8_t bytes[8];\n};", "",
         "static const ProtocolVector kProtocolVectors[] = {"]
    for x in v:
        vals = x["values"] + [0] * (6 - len(x["values"]))
        L.append(f"    {{\"{x['label']}\", 0x{x['canId']:03X}, {{{', '.join(map(str, vals))}}}, {len(x['values'])}, "
                 f"{x['counter']}, {{{', '.join(f'0x{b:02X}' for b in x['bytes'])}}}}},")
    L += ["};", f"static const unsigned kProtocolVectorCount = {len(v)};", ""]
    return "\n".join(L)


# ---------------------------------------------------------------------- TypeScript

def ts(obj) -> str:
    return json.dumps(obj, indent=2, ensure_ascii=False)


def gen_ts(spec: dict) -> str:
    msgs = []
    for m in spec["messages"]:
        msgs.append({
            "name": m["name"], "canId": m["canId"], "sender": m["sender"], "kind": m["kind"], "dlc": m["dlc"],
            "periodMs": m["periodMs"], "counterByte": m["counterByte"], "checksumByte": m["checksumByte"],
            "fields": [{k: f[k] for k in ("key", "start", "length", "signed", "factor", "decimals", "unit",
                                         "validMin", "validMax") } | ({"default": f["default"]} if "default" in f else {})
                       for f in m["fields"]],
        })
    L = [f"// {HEADER}", "// Human-readable spec: docs/protocol/canscope-protocol-v1.md", "",
         f"export const PROTOCOL_VERSION = {spec['protocolVersion']};",
         f"export const SERIAL_PROTOCOL_VERSION = {spec['serialProtocolVersion']};",
         f"export const PROTOCOL_EVIDENCE = {json.dumps(spec['evidence'])};",
         f"export const BUS = {ts(spec['bus'])} as const;",
         f"export const SERIAL = {ts(spec['serial'])} as const;",
         f"export const TIMING = {ts(spec['timing'])} as const;",
         f"export const NODES = {ts(spec['nodes'])} as const;",
         f"export const MESSAGES = {ts(msgs)} as const;",
         f"export const CAN_STATES = {ts(spec['canStates'])} as const;",
         f"export const SEVERITIES = {ts(spec['severities'])} as const;",
         f"export const THRESHOLDS = {ts(spec['thresholds'])} as const;",
         f"export const FAULTS = {ts(spec['faults'])} as const;",
         f"export const DEMO_FAULTS = {ts(spec['demoFaults'])} as const;",
         f"export const ECU_COMMANDS = {ts(spec['ecuCommands'])} as const;",
         f"export const PROFILES = {ts(spec['profiles'])} as const;",
         f"export const COMMON_COMMANDS = {ts(spec['commonCommands'])} as const;",
         f"export const MONITOR_COMMANDS = {ts(spec['monitorCommands'])} as const;",
         "",
         "export type NodeName = (typeof NODES)[number]['name'];",
         "export type NodeRole = (typeof NODES)[number]['role'];",
         "export type FaultCode = (typeof FAULTS)[number]['code'];",
         "export type Severity = (typeof SEVERITIES)[number];",
         "export type DemoFaultName = (typeof DEMO_FAULTS)[number]['name'];",
         "export type ProfileName = (typeof PROFILES)[number];",
         ""]
    return "\n".join(L)


def gen_vec_ts(spec: dict) -> str:
    return "\n".join([f"// {HEADER}", "",
                      f"export const PROTOCOL_VECTORS = {ts(vectors(spec))} as const;", ""])


def main() -> int:
    check = "--check" in sys.argv
    spec = json.loads(SPEC.read_text(encoding="utf-8"))
    validate_spec(spec)
    outputs = {OUT_H: gen_header(spec), OUT_TS: gen_ts(spec), OUT_VEC_H: gen_vec_h(spec),
               OUT_VEC_TS: gen_vec_ts(spec)}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    rel = [str(p.relative_to(ROOT)) for p in stale]
    if check:
        if stale:
            print("STALE generated protocol files (run python tools/protocol/gen_protocol.py):")
            for r in rel:
                print("  " + r)
            return 1
        print(f"protocol generated files up to date ({len(outputs)} files)")
        return 0
    print("wrote: " + (", ".join(rel) if rel else "nothing (already up to date)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
